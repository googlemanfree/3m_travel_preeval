// Fonction de recherche
export function searchCountriesProcedures(query: string): CountryProcedure[] {
  const q = query.toLowerCase();
  return allCountriesProcedures.filter((c) => c.country.toLowerCase().includes(q) || c.slug.includes(q));
}

// Obtenir une procédure par slug
export function getCountryProcedure(slug: string): CountryProcedure | undefined {
  return allCountriesProcedures.find((c) => c.slug === slug);
}

// Obtenir les pays par région
export function getCountriesByRegion(region: "afrique" | "asie" | "europe" | "amerique-nord" | "amerique-centrale" | "amerique-sud" | "oceanie"): CountryProcedure[] {
  const regionRanges: Record<string, [number, number]> = {
    afrique: [0, 54],
    asie: [54, 102],
    europe: [102, 146],
    "amerique-nord": [146, 149],
    "amerique-centrale": [149, 156],
    "amerique-sud": [156, 168],
    oceanie: [168, 184],
  };
  const [start, end] = regionRanges[region] || [0, 0];
  return allCountriesProcedures.slice(start, end);
}
