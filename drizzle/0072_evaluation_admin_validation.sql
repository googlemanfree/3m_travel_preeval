CREATE TABLE IF NOT EXISTS `evaluation_validation_cases` (
  `id` int AUTO_INCREMENT NOT NULL,
  `evaluationId` int NOT NULL,
  `versionNumber` int NOT NULL DEFAULT 1,
  `workflowStatus` varchar(40) NOT NULL DEFAULT 'dossier_recu',
  `aiDraftJson` mediumtext,
  `aiDraftGeneratedAt` timestamp NULL,
  `aiDraftModel` varchar(80),
  `aiDraftWarningsJson` text,
  `aiDraftError` text,
  `adminVersionJson` mediumtext,
  `adminVersionUpdatedAt` timestamp NULL,
  `adminVersionUpdatedBy` varchar(320),
  `firstValidatedBy` varchar(320),
  `firstValidatedAt` timestamp NULL,
  `infoRequestJson` mediumtext,
  `infoRequestedAt` timestamp NULL,
  `infoRequestedBy` varchar(320),
  `publishedReportJson` mediumtext,
  `publishedAt` timestamp NULL,
  `publishedBy` varchar(320),
  `publishedChecklistJson` text,
  `emailSubject` varchar(200),
  `emailSentAt` timestamp NULL,
  `emailError` text,
  `emailClaimedAt` timestamp NULL,
  `createdAt` timestamp NOT NULL DEFAULT (now()),
  `updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE now(),
  CONSTRAINT `evaluation_validation_cases_id` PRIMARY KEY(`id`),
  CONSTRAINT `uq_evaluation_validation_case_version` UNIQUE(`evaluationId`,`versionNumber`),
  INDEX `idx_evaluation_validation_case_status` (`workflowStatus`,`updatedAt`)
);

CREATE TABLE IF NOT EXISTS `evaluation_validation_changes` (
  `id` int AUTO_INCREMENT NOT NULL,
  `evaluationId` int NOT NULL,
  `versionNumber` int NOT NULL DEFAULT 1,
  `adminEmail` varchar(320) NOT NULL,
  `field` varchar(80) NOT NULL,
  `oldValueJson` mediumtext,
  `newValueJson` mediumtext,
  `createdAt` timestamp NOT NULL DEFAULT (now()),
  CONSTRAINT `evaluation_validation_changes_id` PRIMARY KEY(`id`),
  INDEX `idx_evaluation_validation_changes_evaluation` (`evaluationId`,`createdAt`)
);
