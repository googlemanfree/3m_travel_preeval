-- Offres d'emploi, candidatures et signalements. Uniquement de nouvelles tables, idempotent.
CREATE TABLE IF NOT EXISTS job_offers (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  reference VARCHAR(24) NOT NULL,
  organization_id INT NULL,
  employer_name VARCHAR(255) NULL,
  hide_employer_name BOOLEAN NOT NULL DEFAULT FALSE,
  title VARCHAR(255) NOT NULL,
  country_code VARCHAR(2) NOT NULL,
  city VARCHAR(120) NULL,
  domain_id VARCHAR(40) NULL,
  program_ref VARCHAR(80) NULL,
  visa_sponsorship ENUM('employer_sponsors', 'employer_assists', 'candidate_handles') NOT NULL DEFAULT 'employer_assists',
  contract_type ENUM('cdi', 'cdd', 'seasonal', 'interim', 'internship', 'apprenticeship', 'freelance') NOT NULL DEFAULT 'cdi',
  contract_months SMALLINT NULL,
  salary_min DECIMAL(12, 2) NULL,
  salary_max DECIMAL(12, 2) NULL,
  salary_currency CHAR(3) NULL,
  salary_period ENUM('hour', 'month', 'year') NULL,
  salary_visible BOOLEAN NOT NULL DEFAULT FALSE,
  benefits TEXT NULL,
  languages_json JSON NULL,
  diplomas_json JSON NULL,
  experience_min_years SMALLINT NULL,
  start_date DATE NULL,
  start_flexible BOOLEAN NOT NULL DEFAULT TRUE,
  positions_count SMALLINT NOT NULL DEFAULT 1,
  application_deadline DATE NULL,
  description TEXT NOT NULL,
  requirements TEXT NULL,
  status ENUM('draft', 'in_moderation', 'published', 'closed', 'rejected', 'archived') NOT NULL DEFAULT 'draft',
  moderation_note TEXT NULL,
  moderated_by_admin_id INT NULL,
  moderated_at TIMESTAMP NULL,
  published_at TIMESTAMP NULL,
  closed_at TIMESTAMP NULL,
  close_reason ENUM('filled', 'cancelled', 'expired', 'withdrawn_by_admin') NULL,
  version INT NOT NULL DEFAULT 1,
  created_by_admin_id INT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_job_offers_reference (reference),
  INDEX idx_job_offers_country_status (country_code, status),
  INDEX idx_job_offers_org (organization_id, status)
);

CREATE TABLE IF NOT EXISTS job_applications (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  offer_id INT NOT NULL,
  candidate_id INT NOT NULL,
  status ENUM('submitted', 'screening', 'documents_requested', 'shortlisted', 'interview', 'offer_sent', 'accepted', 'hired', 'rejected', 'withdrawn') NOT NULL DEFAULT 'submitted',
  disclosure_level TINYINT NOT NULL DEFAULT 1,
  precheck_json JSON NULL,
  profile_snapshot_json JSON NULL,
  cover_note VARCHAR(1000) NULL,
  rejection_code VARCHAR(40) NULL,
  admin_note TEXT NULL,
  consent_text_version VARCHAR(20) NOT NULL,
  consent_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_status_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_job_applications_offer_candidate (offer_id, candidate_id),
  INDEX idx_job_applications_status (status, last_status_at),
  INDEX idx_job_applications_candidate (candidate_id, status)
);

CREATE TABLE IF NOT EXISTS job_application_events (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  application_id INT NOT NULL,
  actor_type ENUM('candidate', 'admin', 'system') NOT NULL,
  actor_id INT NULL,
  action VARCHAR(80) NOT NULL,
  note VARCHAR(1000) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_job_application_events_app (application_id, created_at)
);

CREATE TABLE IF NOT EXISTS job_offer_reports (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  offer_id INT NOT NULL,
  reporter_candidate_id INT NOT NULL,
  reason ENUM('fees_requested', 'fake_offer', 'discrimination', 'illegal_content', 'wrong_info', 'other') NOT NULL,
  details VARCHAR(1000) NULL,
  status ENUM('open', 'reviewing', 'upheld', 'dismissed') NOT NULL DEFAULT 'open',
  handled_by_admin_id INT NULL,
  decision_note VARCHAR(1000) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_job_offer_reports_offer_reporter (offer_id, reporter_candidate_id),
  INDEX idx_job_offer_reports_status (status, created_at)
);
